// Overlay German fields onto a framework when lang === 'de'.
export function tLaw(framework, lang) {
  if (lang === 'de' && framework.translations && framework.translations.de) {
    const d = framework.translations.de;
    return {
      ...framework,
      name: d.name || framework.name,
      shortDescription: d.shortDescription || framework.shortDescription,
      appliesTo: d.appliesTo || framework.appliesTo,
      whatYouMustDo: d.whatYouMustDo || framework.whatYouMustDo,
      keyDates: d.keyDates || framework.keyDates,
      penalties: d.penalties || framework.penalties,
      regulator: d.regulator || framework.regulator,
    };
  }
  return framework;
}

export const fnLabel = (f, lang) => (lang === 'de' && f.labelDe ? f.labelDe : f.label);
export const fnDesc = (f, lang) => (lang === 'de' && f.descriptionDe ? f.descriptionDe : f.description);
export const catLabel = (c, lang) => (lang === 'de' && c.labelDe ? c.labelDe : c.label);
